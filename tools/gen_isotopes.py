#!/usr/bin/env python
"""Builds js/isotopes.data.js from the Mendeleev database. Usage: python -I tools/gen_isotopes.py <elements.db> <out.js>

Includes every isotope of Z >= 81 with a half-life from 100 ns up to 1e24 s, plus selected lighter radionuclides.
Isotopes not listed behave as stable. Each row is [mass number, half-life in seconds, main decay mode, natural abundance].
"""
import json, sqlite3, sys

db, out = sys.argv[1:3]
c = sqlite3.connect(db)
UNIT = {"sec": 1, "msec": 1e-3, "usec": 1e-6, "nsec": 1e-9, "psec": 1e-12, "fsec": 1e-15, "minute": 60, "hour": 3600, "day": 86400, "year": 31557600,
        "kyear": 31557600e3, "Myear": 31557600e6, "Gyear": 31557600e9, "Tyear": 31557600e12, "Pyear": 31557600e15, "Eyear": 31557600e18, "Zyear": 31557600e21, "Yyear": 31557600e24}
LIGHT = {1: [3], 6: [14], 19: [40], 27: [60], 36: [85], 38: [90], 43: [99], 53: [129, 131, 135], 54: [133, 135], 55: [134, 137], 61: [147], 62: [149, 151]}
MODES = ("A", "B-", "B+", "EC", "SF", "e+", "2B-")
table, natural = {}, {}
for z, A, ab, rad, hl, unit, iso in c.execute("select atomic_number, mass_number, abundance, is_radioactive, half_life, half_life_unit, id from isotopes order by atomic_number, mass_number").fetchall():
    if ab:
        natural.setdefault(z, []).append([A, round(ab / 100, 7)])
    if not rad or hl is None or unit not in UNIT:
        continue
    sec = hl * UNIT[unit]
    if not (z >= 81 and 1e-7 <= sec < 1e24) and not (z in LIGHT and A in LIGHT[z]):
        continue
    best, weight = None, -1
    for mode, inten in c.execute("select mode, intensity from isotopedecaymodes where isotope_id=?", (iso,)):
        m = mode.encode("ascii", "ignore").decode()
        if m in MODES and (inten or 0) > weight:
            best, weight = {"e+": "B+", "2B-": "B-"}.get(m, m), inten or 0
    if best:
        table.setdefault(z, []).append([A, float("%.4g" % sec), best])
with open(out, "w", encoding="utf8", newline="\n") as f:
    f.write("// Generated by tools/gen_isotopes.py from the Mendeleev database. Do not edit by hand.\n")
    f.write("var ISOTOPE_DATA = " + json.dumps(table, separators=(",", ":")) + ";\n")
    f.write("var ISOTOPE_NATURAL = " + json.dumps(natural, separators=(",", ":")) + ";\n")
print(sum(len(v) for v in table.values()), "isotopes")
for z, A in ((92, 238), (92, 235), (90, 234), (91, 234), (88, 226), (86, 222), (84, 218), (82, 214), (83, 214), (84, 214), (82, 210), (83, 210), (84, 210), (93, 239), (54, 135), (53, 135), (6, 14)):
    print(z, A, [r for r in table.get(z, []) if r[0] == A])
